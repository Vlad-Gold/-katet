function NavLinks({
  items,
  route,
  onNavigate,
  ariaLabel,
  className,
}: {
  items: { label: string; path: Route }[]
  route: Route
  onNavigate: (path: Route) => void
  ariaLabel: string
  className: string
}) {
  return (
    <nav className={className} aria-label={ariaLabel}>
      {items.map((item) => (
        <a
          className={route === item.path ? 'nav-link nav-link-active' : 'nav-link'}
          href={toHref(item.path)}
          key={item.path}
          onClick={(event) => { event.preventDefault(); onNavigate(item.path) }}
        >
          {item.label}
          <NavCircuit />
        </a>
      ))}
    </nav>
  )
}

function App() {
  const [route, setRoute] = useState<Route>(getRoute)

  useEffect(() => {
    const handlePopState = () => setRoute(getRoute())
    window.addEventListener('popstate', handlePopState)

    return () => window.removeEventListener('popstate', handlePopState)
  }, [])

  const navigate = (path: Route) => {
    window.history.pushState({}, '', toHref(path))
    setRoute(path)
    window.scrollTo({ top: 0, behavior: 'smooth' })
  }

  return (
    <div className="site-shell">
      <header className="site-header">
        <div className="chrome-inner">
          <div className="brand">
            <img src={logo} alt="KATET" />
            <div
              className="brand-current"
              style={{
                maskImage: `url(${logo})`,
                WebkitMaskImage: `url(${logo})`,
              }}
              aria-hidden="true"
            />
          </div>

          <NavLinks
            ariaLabel="Основная навигация"
            className="site-nav"
            items={navigation}
            onNavigate={navigate}
            route={route}
          />
        </div>
      </header>

      <main className="page-content">
        {route === '/' && <HomePage onContactClick={() => navigate('/contacts')} />}
        {route === '/services' && <ServicesPage onContactClick={() => navigate('/contacts')} />}
        {route === '/contacts' && <ContactsPage />}
        {route === '/legal' && <LegalPage />}
        {route === '/certificates' && <CertificatesPage />}
        {route === '/privacy' && <PrivacyPage />}
      </main>

      <footer className="site-footer">
        <div className="chrome-inner">
          <p>© 2026 KATET</p>
          <NavLinks
            ariaLabel="Юридическая информация"
            className="site-nav site-nav-footer"
            items={footerNavigation}
            onNavigate={navigate}
            route={route}
          />
        </div>
      </footer>
    </div>
  )
}

